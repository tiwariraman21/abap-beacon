"""Technical Specification document (.docx) generated from an FSD analysis.

The ABAPer's first deliverable after the FSD is the technical specification. ABAP Beacon
already knows everything a TS starts with - verdict, feasibility, solution pattern, steps
with building blocks, objects to create with the APIs they use, effort, test scenarios and
the requirement traceability - so it writes the first version. The document is masked
with the same guard as the report (customer names never appear), uses Word's built-in
styles (Title, Heading 1-3, List Bullet, Table Grid) so it follows the reader's template
when pasted, and carries a "generated by ABAP Beacon - review before sign-off" note.
"""

from __future__ import annotations

from datetime import datetime, timezone
from io import BytesIO

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

BRAND = RGBColor(0x0A, 0x6E, 0xD1)
GREY = RGBColor(0x5B, 0x73, 0x8B)


def _table(doc, headers: list[str], rows: list[list[str]], widths_cm: list[float] | None = None) -> None:
    from docx.shared import Cm

    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(9)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            run = cells[i].paragraphs[0].add_run(str(val))
            run.font.size = Pt(9)
    if widths_cm:
        for row in t.rows:
            for i, w in enumerate(widths_cm):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


def _bullets(doc, items: list[str], style: str = "List Bullet") -> None:
    for it in items:
        p = doc.add_paragraph(style=style)
        p.add_run(str(it)).font.size = Pt(10)


def _para(doc, text: str, size: int = 10, italic: bool = False, colour: RGBColor | None = None) -> None:
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.italic = italic
    if colour is not None:
        run.font.color.rgb = colour


def build_technical_spec(payload: dict, mask=None, author: str = "ABAP Beacon") -> bytes:
    """Return the .docx bytes for one analysis payload. `mask` is a callable applied to every string
    that leaves the analysis (the display guard)."""
    m = mask or (lambda s: s)
    plan = payload["plan"]
    fz = payload.get("feasibility") or {}
    reqs = payload["requirements"]
    doc = Document()
    for style_name, size in (("Normal", 10), ("Heading 1", 15), ("Heading 2", 12), ("Heading 3", 11)):
        st = doc.styles[style_name]
        st.font.size = Pt(size)
        if style_name != "Normal":
            st.font.color.rgb = BRAND
    section = doc.sections[0]
    section.footer.paragraphs[0].text = f"Generated by ABAP Beacon on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} · draft for review - not a signed-off specification"
    section.footer.paragraphs[0].runs[0].font.size = Pt(8)
    section.footer.paragraphs[0].runs[0].font.color.rgb = GREY

    # ---------------------------------------------------------------- cover
    t = doc.add_paragraph()
    t.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = t.add_run("Technical Specification")
    r.font.size = Pt(24)
    r.bold = True
    r.font.color.rgb = BRAND
    _para(doc, m(payload["title"]), 14)
    _table(doc, ["Item", "Value"], [
        ["Functional specification", m(payload.get("filename") or "")],
        ["SAP module", payload.get("module") or "-"],
        ["Classification", fz.get("rice", "-")],
        ["Verdict of the analysis", {"reuse": "Reuse existing objects", "extend": "Extend existing objects", "build": "New development"}.get(payload["verdict"], payload["verdict"])],
        ["Coverage by existing code", f"{payload['coverage_pct']} % (weighted)"],
        ["Feasibility", fz.get("verdict", "-")],
        ["Complexity", fz.get("complexity", {}).get("band", "-")],
        ["Estimated effort", f"{plan['effort_hours']} h (incl. design and unit tests)"],
        ["Author", author],
        ["Status", "Draft - generated, to be reviewed by the developer and the functional consultant"],
    ], [5.5, 10.5])
    doc.add_page_break()

    # ---------------------------------------------------------------- 1 purpose
    doc.add_heading("1. Purpose and scope", level=1)
    _para(doc, m(payload.get("summary") or ""))
    scope = [r_ for r_ in reqs if r_.get("kind") == "scope"]
    if scope:
        _para(doc, "Scope statements from the functional specification:", 10)
        _bullets(doc, [m(x["text"]) for x in scope])

    # ---------------------------------------------------------------- 2 feasibility
    if fz:
        doc.add_heading("2. Feasibility, complexity and open points", level=1)
        _para(doc, f"Feasibility: {fz['verdict']}. Complexity {fz['complexity']['band']} (score {fz['complexity']['score']}). "
                   f"FSD quality {fz['quality']['score']}/100. Estimate confidence {fz['confidence']['band']} ({fz['confidence']['pct']} %).")
        for title, items in (("Blocking as written", fz.get("blockers")), ("Changes needed before build", fz.get("changes")), ("Risks", fz.get("risks")), ("Not specified in the FSD", fz.get("missing_nfr"))):
            if items:
                doc.add_heading(title, level=3)
                _bullets(doc, [m(x) for x in items])
        doc.add_heading("Complexity drivers", level=3)
        _bullets(doc, fz["complexity"]["drivers"])
        if fz.get("questions"):
            doc.add_heading("Clarification questions for the functional consultant", level=3)
            _bullets(doc, [m(q) for q in fz["questions"]], "List Number")

    # ---------------------------------------------------------------- 3 existing code
    doc.add_heading("3. Existing code and reuse decision", level=1)
    if payload.get("reuse"):
        _table(doc, ["Object", "Type", "Covers", "What it does"], [[m(c["name"]), c["type"], f"{c['coverage_pct']} %", m(c.get("description") or "")] for c in payload["reuse"]], [4.5, 2.5, 1.8, 7.2])
    else:
        _para(doc, "No existing object covers the requirements; this is a new development.")
    if plan.get("utilities"):
        _para(doc, "Utilities already available in the repository:", 10)
        _bullets(doc, [f"{m(u['name'])} - {m(u['purpose'])}" for u in plan["utilities"]])

    # ---------------------------------------------------------------- 4 solution design
    doc.add_heading("4. Solution design", level=1)
    _para(doc, m(plan["pattern"]), 10)
    _para(doc, m(plan["pattern_reason"]), 10, italic=True)
    if plan.get("alternatives"):
        doc.add_heading("Design alternatives considered", level=3)
        _bullets(doc, [m(a) for a in plan["alternatives"]])
    doc.add_heading("Processing steps", level=2)
    for st in plan["steps"]:
        doc.add_heading(f"4.{st['n']} {m(st['title'])}", level=3)
        _para(doc, m(st["detail"]))
        if st.get("reuse"):
            _para(doc, f"Reuse: {m(st['reuse'])}", 10, italic=True)
        if st.get("blocks"):
            _table(doc, ["Building block", "Kind", "How it is used"], [[m(b["name"]), b["kind"], m(b["purpose"])] for b in st["blocks"]], [5.5, 2.5, 8.0])
        if st.get("addresses"):
            _para(doc, "Implements FSD statements: " + ", ".join(a["id"] for a in st["addresses"]), 9, colour=GREY)

    # ---------------------------------------------------------------- 5 objects
    doc.add_heading("5. Development objects", level=1)
    _table(doc, ["Action", "Object", "Type", "Purpose", "Uses"],
           [[o["action"], m(o["name"]), o["type"], m(o["purpose"]), m(", ".join(o.get("blocks") or []))] for o in plan["objects"]], [1.6, 3.6, 2.6, 4.2, 4.0])
    if plan.get("fsd_blocks"):
        doc.add_heading("Building blocks named in the FSD", level=3)
        _table(doc, ["Named in the FSD", "Note", "Used in"], [[m(b["name"]), m(b["purpose"]), b.get("used_in") or "not needed"] for b in plan["fsd_blocks"]], [4.5, 9.0, 2.5])

    # ---------------------------------------------------------------- 6 requirement traceability
    doc.add_heading("6. Requirement traceability", level=1)
    _para(doc, "Every statement of the functional specification, its status against existing code and where it is implemented.", 10)
    _table(doc, ["#", "Kind", "Statement", "Existing", "Implementation", "h"],
           [[r_["id"], r_["kind"], m(r_["text"]), r_["status"], m(r_["change"]), str(r_["effort_hours"])] for r_ in reqs], [1.0, 2.0, 6.5, 1.6, 4.0, 0.9])

    # ---------------------------------------------------------------- 7 effort, notes, tests
    doc.add_heading("7. Effort estimate", level=1)
    _table(doc, ["Item", "Hours"], [[k.replace("_", " "), str(v)] for k, v in plan["effort_breakdown"].items()] + [["Total", str(plan["effort_hours"])]], [10.0, 3.0])
    if plan.get("s4_notes"):
        doc.add_heading("8. S/4HANA and Clean Core considerations", level=1)
        _bullets(doc, [m(n) for n in plan["s4_notes"]])
    if plan.get("test_scenarios"):
        doc.add_heading("9. Test scenarios", level=1)
        _bullets(doc, [m(t_) for t_ in plan["test_scenarios"]], "List Number")
    if payload.get("ai_notes"):
        doc.add_heading("10. Architect review (AI)", level=1)
        for line in str(payload["ai_notes"]).splitlines():
            if line.strip():
                _para(doc, m(line.strip("#* ").strip()))
    doc.add_heading("Open points and sign-off", level=1)
    _table(doc, ["Role", "Name", "Date", "Signature"], [["Developer", "", "", ""], ["Functional consultant", "", "", ""], ["Solution architect", "", "", ""]], [4.0, 4.5, 3.0, 4.5])

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()
