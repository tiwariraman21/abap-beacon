"""Knowledge base of SAP building blocks.

Maps business intents found in a functional specification ("create a sales
order", "send an e-mail", "post an FI document") to the standard building
blocks a senior ABAPer would reach for: BAPIs, function modules, classes,
CDS views and tables, with S/4HANA notes and pitfalls. Used by the FSD
planner when nothing in the custom repository covers a requirement.

Each intent: keywords (matched against requirement text), blocks
(name, type, purpose), tables/CDS to read, remarks.
"""

from __future__ import annotations

from dataclasses import dataclass


