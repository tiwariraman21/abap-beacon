import re as _re

_KW_CACHE: dict[str, _re.Pattern] = {}


def _kw_pattern(kw: str) -> _re.Pattern:
    if kw not in _KW_CACHE:
        core = _re.escape(kw.strip())
        # word boundaries, tolerate simple plurals / -ing on the last word
        _KW_CACHE[kw] = _re.compile(r"(?<![a-z0-9])" + core + r"(?:s|es|ed|ing)?(?![a-z0-9])")
    return _KW_CACHE[kw]


def match_intents(text: str, limit: int = 3) -> list[tuple[Intent, int]]:
    """Return intents whose keywords appear in text (whole words), best first, with hit counts."""
    t = " ".join(text.lower().split())
    scored: list[tuple[Intent, int]] = []
    for intent in INTENTS:
        hits = 0
        for kw in intent.keywords:
            if _kw_pattern(kw).search(t):
                hits += 2 if " " in kw.strip() else 1     # multi-word keywords are stronger evidence
        if hits:
            scored.append((intent, hits))
    scored.sort(key=lambda x: -x[1])
    return scored[:limit]
