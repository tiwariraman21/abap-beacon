"""Code skeletons from a development plan - the ABAPer starts from compiling objects, not a blank editor.

For every planned object Beacon writes an abapGit-style source file:
  Class            definition with one public method per plan step it implements (typed importing /
                   returning parameters, BAPIRET2 table), an exception class reference, and method
                   bodies that carry the step description and the building blocks as TODO comments
  Exception class  CX_STATIC_CHECK with IF_T100_MESSAGE
  Program          selection screen skeleton, START-OF-SELECTION calling the class, ALV output stub
  Table            DDL-like definition text (fields from the plan purpose) for SE11
  Message class    the messages implied by the error-handling statements
  ABAP Unit        a local test class with one test method per FSD statement the class addresses

Everything is masked with the display guard and marked as generated. The point is not perfect code -
it is the first 20-30 % of typing, with the FSD traceability already in the comments.
"""

from __future__ import annotations

import re
import zipfile
from datetime import datetime, timezone
from io import BytesIO


_STOP = {"THE", "A", "AN", "IN", "OF", "AND", "TO", "FOR", "ON", "WITH", "BY", "AT", "FROM", "INTO", "IS", "ARE", "BE", "OR", "AS", "THAT", "THIS", "IT", "ITS", "PER"}


def _ident(text: str, limit: int = 30) -> str:
    words = [w for w in re.sub(r"[^A-Za-z0-9]+", " ", text).upper().split() if w not in _STOP]
    t = "_".join(words) or "STEP"
    t = re.sub(r"^\d", "X", t)
    return t[:limit].rstrip("_")


def _wrap(text: str, width: int = 90, prefix: str = '"   ') -> list[str]:
    words, lines, cur = text.split(), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > width:
            lines.append(prefix + cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        lines.append(prefix + cur)
    return lines


def _header(kind: str, name: str, title: str) -> list[str]:
    return [f'"! {kind} {name} - generated by ABAP Beacon on {datetime.now(timezone.utc).strftime("%Y-%m-%d")}',
            f'"! Source: FSD "{title}"', '"! Review every TODO before activation; this is a starting point, not a finished object.', ""]


def _class(obj: dict, steps: list[dict], payload: dict, m) -> str:
    name = obj["name"].lower()
    excl = next((o["name"] for o in payload["plan"]["objects"] if o["name"].startswith("ZCX_")), "cx_static_check").lower()
    my_steps = [s for s in steps if s["n"] in (obj.get("steps") or [])] or steps[:1]
    lines = _header("Class", obj["name"], m(payload["title"]))
    lines += [f"CLASS {name} DEFINITION PUBLIC FINAL CREATE PUBLIC.", "  PUBLIC SECTION.", "    TYPES: ty_return TYPE STANDARD TABLE OF bapiret2 WITH DEFAULT KEY.", ""]
    lines += ['    "! Purpose: ' + m(obj["purpose"]), ""]
    for st in my_steps:
        meth = _ident(st["title"])
        lines += [f'    "! Step {st["n"]}: {m(st["title"])}', f'    "! Addresses FSD statements: {", ".join(st["requirements"]) or "-"}',
                  f"    METHODS {meth.lower()}", "      IMPORTING iv_key       TYPE string", "                iv_test_mode TYPE abap_bool DEFAULT abap_false",
                  "      EXPORTING et_return    TYPE ty_return", "      RETURNING VALUE(rv_ok) TYPE abap_bool", f"      RAISING   {excl}.", ""]
    lines += ["  PROTECTED SECTION.", "  PRIVATE SECTION.", "    DATA mt_log TYPE ty_return.", "    METHODS add_message IMPORTING is_return TYPE bapiret2.", "ENDCLASS.", "", "", f"CLASS {name} IMPLEMENTATION.", ""]
    for st in my_steps:
        meth = _ident(st["title"]).lower()
        lines += [f"  METHOD {meth}.", f'    " Step {st["n"]}: {m(st["title"])}']
        lines += _wrap(m(st["detail"]), prefix='    " ')
        if st.get("blocks"):
            lines.append('    " Building blocks:')
            for b in st["blocks"]:
                lines.append(f'    "   - {m(b["name"])} ({b["kind"]}): {m(b["purpose"])[:80]}')
        if st.get("addresses"):
            lines.append('    " FSD statements implemented here:')
            for a in st["addresses"]:
                lines.append(f'    "   {a["id"]}: {m(a["text"])[:100]}')
        lines += ["    CLEAR: et_return, rv_ok.", "    " + "TODO" + ": implement - keep one BAPI/API call per data area, fill the *_X structures, COMMIT once.",
                  "    IF iv_test_mode = abap_true.", "      rv_ok = abap_true.", "      RETURN.", "    ENDIF.", "    rv_ok = abap_true.", "  ENDMETHOD.", ""]
    lines += ["  METHOD add_message.", "    APPEND is_return TO mt_log.", "  ENDMETHOD.", "ENDCLASS."]
    return "\n".join(lines) + "\n"


def _unit_test(obj: dict, steps: list[dict], payload: dict, m) -> str:
    name = obj["name"].lower()
    my_steps = [s for s in steps if s["n"] in (obj.get("steps") or [])] or steps[:1]
    lines = _header("ABAP Unit local test class for", obj["name"], m(payload["title"]))
    lines += [f"CLASS ltc_{name[4:34]} DEFINITION FINAL FOR TESTING DURATION SHORT RISK LEVEL HARMLESS.", "  PRIVATE SECTION.", f"    DATA mo_cut TYPE REF TO {name}.", "    METHODS setup."]
    tests = [(a["id"], a["text"]) for st in my_steps for a in (st.get("addresses") or [])][:12]
    for rid, text in tests:
        lines.append(f'    "! {rid}: {m(text)[:90]}')
        lines.append(f"    METHODS {rid.lower()}_{_ident(text, 24).lower()} FOR TESTING.")
    lines += ["ENDCLASS.", "", f"CLASS ltc_{name[4:34]} IMPLEMENTATION.", "  METHOD setup.", "    mo_cut = NEW #( ).", "  ENDMETHOD."]
    for rid, text in tests:
        lines += [f"  METHOD {rid.lower()}_{_ident(text, 24).lower()}.", f'    " Given / when / then for {rid}', "    DATA(lv_ok) = mo_cut->" + _ident(my_steps[0]["title"]).lower() + "( iv_key = 'TEST' iv_test_mode = abap_true ).",
                  "    cl_abap_unit_assert=>assert_true( act = lv_ok msg = '" + rid + " not satisfied' ).", "  ENDMETHOD."]
    lines += ["ENDCLASS."]
    return "\n".join(lines) + "\n"


def _exception(obj: dict, payload: dict, m) -> str:
    name = obj["name"].lower()
    msg = next((o["name"] for o in payload["plan"]["objects"] if o["type"].startswith("Message")), "ZMSG")
    lines = _header("Exception class", obj["name"], m(payload["title"]))
    lines += [f"CLASS {name} DEFINITION PUBLIC INHERITING FROM cx_static_check FINAL CREATE PUBLIC.", "  PUBLIC SECTION.", "    INTERFACES if_t100_message.", "    INTERFACES if_t100_dyn_msg.",
              "    CONSTANTS:", "      BEGIN OF technical_error,", f"        msgid TYPE symsgid VALUE '{msg}',", "        msgno TYPE symsgno VALUE '001',", "        attr1 TYPE scx_attrname VALUE 'MV_TEXT',",
              "        attr2 TYPE scx_attrname VALUE '', attr3 TYPE scx_attrname VALUE '', attr4 TYPE scx_attrname VALUE '',", "      END OF technical_error,",
              "      BEGIN OF application_error,", f"        msgid TYPE symsgid VALUE '{msg}',", "        msgno TYPE symsgno VALUE '002',", "        attr1 TYPE scx_attrname VALUE 'MV_TEXT',",
              "        attr2 TYPE scx_attrname VALUE '', attr3 TYPE scx_attrname VALUE '', attr4 TYPE scx_attrname VALUE '',", "      END OF application_error.",
              "    DATA mv_text TYPE string READ-ONLY.", "    METHODS constructor IMPORTING textid LIKE if_t100_message=>t100key OPTIONAL previous LIKE previous OPTIONAL text TYPE string OPTIONAL.",
              "ENDCLASS.", "", f"CLASS {name} IMPLEMENTATION.", "  METHOD constructor ##ADT_SUPPRESS_GENERATION.", "    super->constructor( previous = previous ).", "    mv_text = text.",
              "    CLEAR me->textid.", "    IF textid IS INITIAL.", "      if_t100_message~t100key = if_t100_message=>default_textid.", "    ELSE.", "      if_t100_message~t100key = textid.", "    ENDIF.",
              "  ENDMETHOD.", "ENDCLASS."]
    return "\n".join(lines) + "\n"


def _program(obj: dict, payload: dict, m) -> str:
    name = obj["name"].lower()
    cls = next((o["name"] for o in payload["plan"]["objects"] if o["type"].startswith("Class") and o["action"] == "create"), "zcl_todo").lower()
    lines = _header("Program", obj["name"], m(payload["title"]))
    lines += [f"REPORT {name}.", "", '"! ' + m(obj["purpose"]), "", "TABLES sscrfields.", "SELECTION-SCREEN BEGIN OF BLOCK b1 WITH FRAME TITLE TEXT-001.",
              "  PARAMETERS: p_test TYPE abap_bool AS CHECKBOX DEFAULT abap_true.", "  SELECT-OPTIONS: s_key FOR sy-uname NO INTERVALS.   \" TODO: replace with the real key field",
              "SELECTION-SCREEN END OF BLOCK b1.", "", "CLASS lcl_main DEFINITION FINAL.", "  PUBLIC SECTION.", "    METHODS run.", "  PRIVATE SECTION.", f"    DATA mo_api TYPE REF TO {cls}.",
              "    METHODS display IMPORTING it_return TYPE bapiret2_t.", "ENDCLASS.", "", "CLASS lcl_main IMPLEMENTATION.", "  METHOD run.", "    mo_api = NEW #( ).",
              "    DATA lt_return TYPE bapiret2_t.", "    \" TODO: select the items to process (status table / selection) and call the class method per item",
              "    display( lt_return ).", "  ENDMETHOD.", "  METHOD display.", "    TRY.", "        cl_salv_table=>factory( IMPORTING r_salv_table = DATA(lo_alv) CHANGING t_table = it_return ).",
              "        lo_alv->get_functions( )->set_all( abap_true ).", "        lo_alv->get_columns( )->set_optimize( abap_true ).", "        lo_alv->display( ).",
              "      CATCH cx_salv_msg INTO DATA(lx_msg).", "        MESSAGE lx_msg TYPE 'E'.", "    ENDTRY.", "  ENDMETHOD.", "ENDCLASS.", "", "START-OF-SELECTION.", "  NEW lcl_main( )->run( )."]
    return "\n".join(lines) + "\n"


def _table(obj: dict, payload: dict, m) -> str:
    name = obj["name"]
    lines = _header("Table (SE11 / DDL)", name, m(payload["title"]))
    lines += [f"@EndUserText.label : '{m(obj['purpose'])[:60]}'", "@AbapCatalog.enhancement.category : #NOT_EXTENSIBLE", "@AbapCatalog.tableCategory : #TRANSPARENT",
              "@AbapCatalog.deliveryClass : #A", "@AbapCatalog.dataMaintenance : #ALLOWED", f"define table {name.lower()} {{", "  key client            : abap.clnt not null;"]
    low = obj["purpose"].lower()
    if "status" in low or "stat" in name.lower():
        lines += ["  key object_key        : abap.char(40) not null;", "  key change_ts         : timestampl not null;", "  status                : abap.char(10);   // NEW | RETRY | ERROR | DONE",
                  "  attempts              : abap.int2;", "  next_run              : timestampl;", "  payload_hash          : abap.char(40);", "  last_msgty            : abap.char(1);", "  last_message          : abap.char(220);"]
    elif "map" in low:
        lines += ["  key source_value      : abap.char(40) not null;", "  key mapping_type      : abap.char(10) not null;", "  target_value          : abap.char(40);", "  valid_from            : abap.dats;", "  valid_to              : abap.dats;"]
    elif "config" in low or "cfg" in name.lower():
        lines += ["  key parameter         : abap.char(40) not null;", "  key seqno             : abap.numc(3) not null;", "  value_low             : abap.char(80);", "  value_high            : abap.char(80);", "  active                : abap_boolean;"]
    else:
        lines += ["  key document_key      : abap.char(40) not null;", "  key seqno             : abap.numc(4) not null;", "  value                 : abap.char(80);"]
    lines += ["  created_by            : syuname;", "  created_at            : timestampl;", "  changed_by            : syuname;", "  changed_at            : timestampl;", "}"]
    return "\n".join(lines) + "\n"


def _messages(obj: dict, payload: dict, m) -> str:
    lines = _header("Message class", obj["name"], m(payload["title"]))
    lines += ["000  &1 &2 &3 &4", "001  Technical error: &1", "002  Application error: &1", "003  &1 processed successfully", "004  Retry &1 of &2 scheduled for &3", "005  No authorization for &1"]
    n = 6
    for r in payload["requirements"]:
        if r.get("kind") in ("validation", "error_handling") and n < 40:
            lines.append(f"{n:03d}  {m(r['text'])[:70]}")
            n += 1
    return "\n".join(lines) + "\n"


def build_code_package(payload: dict, mask=None) -> tuple[bytes, list[str]]:
    """Return (zip bytes, list of file names)."""
    m = mask or (lambda s: s)
    plan = payload["plan"]
    steps = plan["steps"]
    files: dict[str, str] = {}
    readme = [f"# Generated code package - {m(payload['title'])}", "", f"Pattern: {m(plan['pattern'])}", "", "Files (abapGit layout, one per object) - review every TODO:", ""]
    for o in plan["objects"]:
        if o["action"] == "reuse":
            continue
        t = o["type"]
        n = o["name"].lower()
        if t.startswith("Class") or t.startswith("Consumer proxy"):
            files[f"src/{n}.clas.abap"] = _class(o, steps, payload, m)
            files[f"src/{n}.clas.testclasses.abap"] = _unit_test(o, steps, payload, m)
        elif t.startswith("Exception"):
            files[f"src/{n}.clas.abap"] = _exception(o, payload, m)
        elif t.startswith("Program") or t.startswith("Report"):
            files[f"src/{n}.prog.abap"] = _program(o, payload, m)
        elif t.startswith("Table"):
            files[f"src/{n}.tabl.ddl.txt"] = _table(o, payload, m)
        elif t.startswith("Message"):
            files[f"src/{n}.msag.txt"] = _messages(o, payload, m)
        else:
            files[f"src/{n}.todo.txt"] = "\n".join(_header(t, o["name"], m(payload["title"])) + [m(o["purpose"]), "", "Uses: " + ", ".join(m(b) for b in (o.get("blocks") or []))]) + "\n"
        readme.append(f"- `{o['name']}` ({t}): {m(o['purpose'])}")
    readme += ["", "Traceability: every method carries the FSD statement ids it implements; the local test class has one test per statement.", ""]
    files["README.md"] = "\n".join(readme)
    files[".abapgit.xml"] = ('<?xml version="1.0" encoding="utf-8"?>\n<abapGit version="v1.0.0" serializer="LCL_OBJECT_ABAPGIT" serializer_version="v1.0.0">\n <asx:abap xmlns:asx="http://www.sap.com/abapxml" version="1.0">\n  <asx:values>\n   <DATA>\n    <MASTER_LANGUAGE>E</MASTER_LANGUAGE>\n    <STARTING_FOLDER>/src/</STARTING_FOLDER>\n    <FOLDER_LOGIC>PREFIX</FOLDER_LOGIC>\n   </DATA>\n  </asx:values>\n </asx:abap>\n</abapGit>\n')
    buf = BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path, content in files.items():
            z.writestr(path, content)
    return buf.getvalue(), sorted(files)
